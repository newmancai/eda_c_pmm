% 示例字符串数据，包含注释行
raw_data = ['-26.9133751604029 111.095937009636\n' ...
            '-31.2087746364068 143.695221736438\n' ...
            '! This is a comment line\n' ...
            '-13.1661691075314 -173.213967402163\n' ...
            '! Another comment\n' ...
            '-7.94670971392043 -58.4017596377577\n'];

% 使用 regexprep 删除所有注释行，保留换行符
 % 使用 regexprep 删除以 ! 开头的行
cleaned_data = regexprep(raw_data, '^[^\n]*![^\n]*\n', '', 'lineanchors');

% 输出清理后的数据
disp('清理后的数据:');
fprintf(cleaned_data);
